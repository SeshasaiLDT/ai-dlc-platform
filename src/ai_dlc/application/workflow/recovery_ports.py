"""Durable execution persistence contract; transactions never span remote calls."""

from typing import Protocol

from .recovery_models import ExecutionRecord


class ExecutionRepository(Protocol):
    def create(self, record: ExecutionRecord) -> ExecutionRecord: ...
    def get(self, execution_id: str) -> ExecutionRecord: ...
    def claim(self, execution_id: str, token: str, now, seconds: float) -> ExecutionRecord: ...
    def save(self, record: ExecutionRecord, token: str, now) -> ExecutionRecord: ...
    def cancel(self, execution_id: str, now) -> ExecutionRecord: ...
